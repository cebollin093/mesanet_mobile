class Usuario {
  final String id;
  final String nombre;
  final String apellido;
  final String dni;
  final String email;
  final String carreraId;
  final String rol;

  Usuario({
    required this.id,
    required this.nombre,
    required this.apellido,
    required this.dni,
    required this.email,
    required this.carreraId,
    required this.rol,
  });
}